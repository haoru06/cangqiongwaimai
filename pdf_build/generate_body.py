def make_table(story, header, rows, ratios, cap=None):
    data = [[Paragraph('<b>%s</b>' % c, th_st) for c in header]]
    for r in rows:
        data.append([Paragraph(c, td_st) if i == 0 else Paragraph(c, td_st) for i, c in enumerate(r)])
    widths = [x * AVAIL_W * 0.98 for x in ratios]
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_EVEN if i % 2 == 1 else TABLE_ROW_ODD))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 8)); story.append(t)
    if cap:
        story.append(Spacer(1, 4)); story.append(Paragraph(cap, caption))
    story.append(Spacer(1, 8))

