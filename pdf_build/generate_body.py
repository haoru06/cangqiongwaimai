def code_block(story, code_text, label=None):
    paras = []
    if label:
        paras.append(Paragraph(label, st('CodeLabel', fontName='MSYH-B', fontSize=8.6,
                     leading=13, textColor=TEXT_MUTED, spaceAfter=2)))
    AMP, LT, GT = chr(38), chr(60), chr(62)
    NBSP = AMP + 'nbsp;'
    CJK_CHARS = u'一-鿿　-〿＀-￯「」·'
    CJK_RE = re.compile('[' + CJK_CHARS + ']+')
    def _cjk(m):
        return '<font name="MSYH">' + m.group(0) + '</font>'
    for line in code_text.splitlines():
        esc = line.replace(AMP, AMP + 'amp;').replace(LT, AMP + 'lt;').replace(GT, AMP + 'gt;')
        esc = esc.replace(' ', NBSP)
        esc = CJK_RE.sub(_cjk, esc)
        paras.append(Paragraph(esc, code_st))
    t = Table([[paras]], colWidths=[AVAIL_W * 0.96])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), TABLE_STRIPE),
        ('LINEBEFORE', (0, 0), (0, -1), 2.2, ACCENT),
        ('LEFTPADDING', (0, 0), (-1, -1), 12),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 7),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 7),
    ]))
    t.hAlign = 'CENTER'
    story.append(Spacer(1, 4)); story.append(t); story.append(Spacer(1, 8))

