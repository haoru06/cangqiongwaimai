def box(d, x, y, w, h, title, lines=None, fill=ACCENT_SOFT, border=ACCENT,
        ts=9.5, ds=7.8, tcolor=None, bw=1.0):
    d.add(Rect(x, y, w, h, rx=4, ry=4, fillColor=fill, strokeColor=border, strokeWidth=bw))
    cx = x + w / 2.0
    lines = lines or []
    if lines:
        d.add(String(cx, y + h - ts - 4, title, fontName='MSYH-B', fontSize=ts,
                     fillColor=tcolor or TEXT_PRIMARY, textAnchor='middle'))
        ly = y + h - ts - 4 - ds - 3.2
        for ln in lines:
            d.add(String(cx, ly, ln, fontName='MSYH', fontSize=ds, fillColor=TEXT_MUTED, textAnchor='middle'))
            ly -= ds + 2.4
    else:
        d.add(String(cx, y + (h - ts) / 2.0 + 0.5, title, fontName='MSYH-B', fontSize=ts,
                     fillColor=tcolor or TEXT_PRIMARY, textAnchor='middle'))

def arrow(d, x1, y1, x2, y2, color=TEXT_PRIMARY, w=0.9, dashed=False, label=None,
          ls=7.3, lcolor=None, lox=0, loy=3):
    import math
    ang = math.atan2(y2 - y1, x2 - x1)
    ah = 5.0
    bx, by = x2 - ah * math.cos(ang), y2 - ah * math.sin(ang)
    d.add(Line(x1, y1, bx, by, strokeColor=color, strokeWidth=w,
               strokeDashArray=[2.5, 2.5] if dashed else None))
    d.add(Polygon(points=[x2, y2, bx + ah*0.42*math.cos(ang+1.57), by + ah*0.42*math.sin(ang+1.57),
                          bx + ah*0.42*math.cos(ang-1.57), by + ah*0.42*math.sin(ang-1.57)],
                  fillColor=color, strokeColor=None))
    if label:
        mx, my = (x1 + x2) / 2.0 + lox, (y1 + y2) / 2.0 + loy
        d.add(String(mx, my, label, fontName='MSYH', fontSize=ls,
                     fillColor=lcolor or TEXT_MUTED, textAnchor='middle'))

def vlabel(d, x, y, text, size=7.3, color=None, anchor='middle', bold=False):
    d.add(String(x, y, text, fontName='MSYH-B' if bold else 'MSYH', fontSize=size,
                 fillColor=color or TEXT_MUTED, textAnchor=anchor))

